#!/usr/bin/env python3
"""Small client for the Jules REST API (https://jules.googleapis.com/v1alpha). The key comes from the env JULES_API_KEY and is never printed."""
import json, os, sys, urllib.request, urllib.error

BASE = "https://jules.googleapis.com/v1alpha"
KEY = os.environ["JULES_API_KEY"]


def call(method, path, body=None):
    req = urllib.request.Request(BASE + path, method=method, data=json.dumps(body).encode() if body is not None else None,
                                 headers={"x-goog-api-key": KEY, "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            raw = r.read().decode() or "{}"
            return json.loads(raw)
    except urllib.error.HTTPError as e:
        return {"_http_error": e.code, "_body": e.read().decode()[:1500]}


def short(s, n=600):
    s = (s or "").replace("\r", "")
    return s if len(s) <= n else s[:n] + " ...[cut]"


def describe(a):
    t = a.get("createTime", "")[11:19]
    for k in ("planGenerated", "planApproved", "userMessaged", "agentMessaged", "progressUpdated", "sessionCompleted", "sessionFailed"):
        if k in a:
            v = a[k]
            if k == "planGenerated":
                steps = "; ".join(s.get("title", "") for s in v.get("plan", {}).get("steps", []))
                txt = "plan: " + steps
            elif k == "userMessaged":
                txt = v.get("userMessage", "")
            elif k == "agentMessaged":
                txt = v.get("agentMessage", "")
            elif k == "progressUpdated":
                txt = (v.get("title", "") + " - " + v.get("description", "")).strip(" -")
            elif k == "sessionFailed":
                txt = v.get("reason", "")
            else:
                txt = ""
            line = "- %s **%s** %s" % (t, k, short(txt.replace("\n", " "), 500))
            for art in a.get("artifacts", []) or []:
                if "bashOutput" in art:
                    b = art["bashOutput"]
                    line += "\n    - `%s` exit %s: %s" % (short(b.get("command", ""), 160), b.get("exitCode"), short((b.get("output") or "").replace("\n", " | "), 300))
                if "changeSet" in art:
                    line += "\n    - changeSet"
            return line
    return "- %s (activity %s)" % (t, list(a.keys()))


def status(limit_sessions=6, limit_acts=14):
    data = call("GET", "/sessions?pageSize=%d" % limit_sessions)
    out = ["# Jules status", "", "Generated by tools/jules_api.py (workflow jules-api). Newest session first.", ""]
    if "_http_error" in data:
        out.append("API error %s: %s" % (data["_http_error"], data["_body"]))
        return "\n".join(out) + "\n"
    for s in data.get("sessions", []):
        sid = s.get("id") or s.get("name", "").split("/")[-1]
        out.append("## %s  [%s]" % (s.get("title") or sid, s.get("state")))
        out.append("session `%s`, created %s, updated %s, %s" % (sid, s.get("createTime"), s.get("updateTime"), s.get("url", "")))
        for o in s.get("outputs", []) or []:
            pr = o.get("pullRequest")
            if pr:
                out.append("PR: %s (%s)" % (pr.get("url"), pr.get("title")))
        acts = call("GET", "/sessions/%s/activities?pageSize=100" % sid)
        items = acts.get("activities", []) if "_http_error" not in acts else []
        if "_http_error" in acts:
            out.append("activities error %s: %s" % (acts["_http_error"], acts["_body"]))
        items = sorted(items, key=lambda a: a.get("createTime", ""))[-limit_acts:]
        out.append("")
        out.extend(describe(a) for a in items)
        out.append("")
    return "\n".join(out) + "\n"


def main():
    action = sys.argv[1]
    sid = os.environ.get("SESSION_ID", "").strip()
    prompt = os.environ.get("PROMPT", "")
    if action == "status":
        text = status()
        open("JULES_STATUS.md", "w").write(text)
        print(text[:3000])
    elif action == "message":
        print(json.dumps(call("POST", "/sessions/%s:sendMessage" % sid, {"prompt": prompt})))
    elif action == "approve":
        print(json.dumps(call("POST", "/sessions/%s:approvePlan" % sid, {})))
    elif action == "create":
        body = {"prompt": prompt, "title": os.environ.get("TITLE") or "Task from Claude",
                "sourceContext": {"source": "sources/github/Pompadoure/SmartTube",
                                  "githubRepoContext": {"startingBranch": os.environ["BRANCH"]}},
                "requirePlanApproval": False, "automationMode": "AUTO_CREATE_PR"}
        res = call("POST", "/sessions", body)
        print(json.dumps({k: res.get(k) for k in ("name", "id", "state", "url", "_http_error", "_body")}))
    elif action == "sources":
        print(json.dumps(call("GET", "/sources?pageSize=20"))[:2000])
    else:
        sys.exit("unknown action")


main()
